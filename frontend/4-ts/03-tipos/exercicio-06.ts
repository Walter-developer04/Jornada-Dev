// O tipo primitivo "boolean" no TypeScript.
//
// Para que isso serve?
// Representa valores lógicos binários: verdadeiro (true) ou falso (false). É essencial para controle de fluxo e validações condicionais.
//
// Qual comportamento devo observar?
// Apenas "true" e "false" são aceitos como valores válidos para essas variáveis pelo sistema de tipos.

const usuarioLogado: boolean = true;
const autenticacaoPendente: boolean = false;

console.log(usuarioLogado);
console.log(autenticacaoPendente);
