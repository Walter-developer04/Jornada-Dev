// ============================================================
// ASSUNTO: for
// ============================================================

// Conta de 1 até 5
for (let numero = 1; numero <= 5; numero++) {
    console.log("Número:", numero);
}

// Percorre um array de frutas
const frutas = ["banana", "maçã", "uva", "laranja", "pêra"];

for (let i = 0; i < frutas.length; i++) {
    console.log("Fruta:", frutas[i]);
}

// Conta de 10 até 1 (contagem regressiva)
for (let contagem = 10; contagem >= 1; contagem--) {
    console.log("Contagem regressiva:", contagem);
}
