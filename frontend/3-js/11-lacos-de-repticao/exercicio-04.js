// Percorre cada valor de um array
const cidades = ["Salvador", "Recife", "Fortaleza", "Manaus"];

for (const cidade of cidades) {
    console.log("Cidade:", cidade);
}

// Percorre cada valor de um array de números
const notas = [7, 8, 5, 9, 6];

for (const nota of notas) {
    console.log("Nota:", nota);
}
