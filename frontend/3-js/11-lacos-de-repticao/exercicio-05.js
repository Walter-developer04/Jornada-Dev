// ASSUNTO: while
// ============================================================

// A condição é verificada antes de cada repetição
let numero = 1;

while (numero <= 5) {
    console.log("Número:", numero);
    numero++; // Atualiza o número a cada repetição
}

// Conta regressiva com while
let contagem = 5;

while (contagem >= 1) {
    console.log("Contagem:", contagem);
    contagem--;
}

console.log("Fim!");
