"use strict"
// typeof com variáveis

let nome = "Maria";
let idade = 25;
let altura = 1.70;
let logado = true;

console.log(typeof nome);    // "string"
console.log(typeof idade);   // "number"
console.log(typeof altura);  // "number"
console.log(typeof logado);  // "boolean"

let numeroTexto = "123";
console.log(typeof numeroTexto); // "string" (número entre aspas é texto)