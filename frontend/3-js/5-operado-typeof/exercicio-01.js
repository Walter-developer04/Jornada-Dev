/*
  =============================================
  OPERADO TYPEOF - O que é ? e para que serve ?
  =============================================
*/
// O que é: typeof é um operador, ou seja, uma palavra
// especial que já vem pronta no JavaScript.
// É como perguntar "o que é você?" para um valor,
// e ele sempre responde em texto (string).
//
// Para que serve: O typeof descobre o tipo de um valor.
//
// Exemplo:
// typeof 10 -> "number"
// typeof "oi" -> "string"

console.log(typeof 10);  //  "number"
console.log(typeof 10.5); // "number" 
console.log(typeof "olá"); // "string"
console.log(typeof true); // "boolean"
console.log(typeof false); // "boolean"